import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
import {writeFile,mkdir} from 'node:fs/promises';
const outputDir=process.env.TEST_OUTPUT_DIR??'test-output';
await mkdir(outputDir,{recursive:true});
const url='http://127.0.0.1:5190';
const token=process.env.PROMPTQL_VISITOR_TOKEN;
if(!token)throw Error('Set PROMPTQL_VISITOR_TOKEN to a captured X-PromptQL-Visitor-Token value. Never use the VM user JWT: it expires and is the wrong identity.');
const b=await chromium.connectOverCDP('http://127.0.0.1:9222');
const context=await b.newContext({viewport:{width:1400,height:950}});
const page=await context.newPage();
const report=[];
const ok=(name,condition)=>{report.push({name,pass:!!condition});console.log(condition?'PASS':'FAIL',name);assert.ok(condition,name);};
let sentInput=null;
try {
 const unauth=await fetch(`${url}/api/state`);
 ok('unauthenticated state rejected',unauth.status===401);
 const invalid=await fetch(`${url}/api/state`,{headers:{'X-PromptQL-Visitor-Token':'not-a-token'}});
 ok('invalid token rejected',invalid.status===401);
 const apiHeaders={'X-PromptQL-Visitor-Token':token,'Content-Type':'application/json'};
 const before=await (await fetch(`${url}/api/state`,{headers:apiHeaders})).json();
 ok('valid acting-user request reaches platform',Number.isInteger(before.revision)&&before.user?.id);
 await page.route('**/api/**',async route=>{
   const req=route.request();
   const headers={...req.headers(),'x-promptql-visitor-token':token};
   if(req.url().endsWith('/api/save')){
     sentInput={...req.postDataJSON(),qa:true};
     await route.continue({headers,postData:JSON.stringify(sentInput)});
   }else await route.continue({headers});
 });
 await page.goto(url,{waitUntil:'networkidle'});
 await page.getByRole('status').filter({hasText:'Shared review loaded.'}).waitFor();
 ok('production app displays authenticated identity',(await page.locator('.review-banner').innerText()).includes(before.user.name));
 await page.locator('button[title="Comment mode"]').click();
 const target=page.locator('[data-anno-id="spec.lede"]');
 await target.scrollIntoViewIfNeeded();
 const box=await target.boundingBox();
 await page.mouse.click(box.x+10,box.y+10);
 await page.locator('.ca-composer-input').fill('QA: annotation Save all closes the review round and delivers its full state to this bot.');
 await page.keyboard.press('Enter');
 await page.getByRole('button',{name:/Save all/}).click();
 await page.getByRole('status').filter({hasText:'Saved review and posted'}).waitFor({timeout:65000});
 ok('Save all acknowledged real artifact + bot message',!!sentInput);
 const after=await (await fetch(`${url}/api/state`,{headers:apiHeaders})).json();
 ok('shared revision advances once',after.revision===before.revision+1);
 const saved=after.doc.threads.find(t=>t.closedRoundId===sentInput.saveId);
 ok('sent review is closed and authored by requester',saved?.comments[0].author.id===before.user.id);
 ok('round preserves artifact HTML and comments',after.doc.rounds.at(-1).artifactSnapshot.includes('data-anno-id')&&after.doc.rounds.at(-1).threads.length===1);
 const duplicate=await fetch(`${url}/api/save`,{method:'POST',headers:apiHeaders,body:JSON.stringify(sentInput)});
 const dupe=await duplicate.json();
 ok('same Save ID replays acknowledgment without second message',duplicate.status===200 && dupe.duplicate===true);
 const conflict=await fetch(`${url}/api/save`,{method:'POST',headers:apiHeaders,body:JSON.stringify({...sentInput,saveId:crypto.randomUUID()})});
 ok('stale revision rejected rather than overwriting',conflict.status===409);
 const altered=structuredClone(after.doc);
 altered.threads.find(t=>t.id===saved.id).comments[0].body[0].value='Illegal history rewrite';
 const edit=await fetch(`${url}/api/save`,{method:'POST',headers:apiHeaders,body:JSON.stringify({...sentInput,saveId:crypto.randomUUID(),revision:after.revision,doc:altered})});
 ok('server rejects immutable history rewrite',edit.status===400);
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('status').filter({hasText:'Shared review loaded.'}).waitFor();
 await page.getByRole('button',{name:/Sent rounds/}).click();
 ok('saved history reloads in app',(await page.locator('.review-history').innerText()).includes('read-only'));
 await page.screenshot({path:`${outputDir}/app-headed.png`});
 console.log('MESSAGE_ID',dupe.messageId);
 await writeFile(`${outputDir}/save-qa.json`,JSON.stringify({saveId:sentInput.saveId,messageId:dupe.messageId,revision:after.revision},null,2));
} finally {
 await writeFile(`${outputDir}/app-results.json`,JSON.stringify({report,authScope:'Local headed QA injects acting-user token on /api requests only. Hosted visitor consent not automated.'},null,2));
 await context.close();await b.close();
}